/** 她的招表按 `关系.$已达最高关系阶段` 查表，**不从 MVU 读**（§5.8 字段落位表）；
 * 因为是历史最高段而非当前段，关系回退后她不换回低段套（草案 §6.4 第八轮换锚点）。
 *
 * 第一版只有 4 恋人与 5 亲密恋人两套，**其余五段推迟到第二版**（草案 §6.4 第二条）。
 * 面板编辑「关系」可以把 `$已达最高关系阶段` 推到订婚／结婚，那时本表查不到——
 * 组件必须走 `herSkillSet()` 的 note 分支如实说明，不得就地编一套招。 */
const HER_SKILL_SET: Partial<Record<Stage, readonly [string, string, string, string]>> = {
  恋人: ['课代表式回击', '板着脸的荤话', '一本正经', '重新板起脸'],
  亲密恋人: ['贴着耳朵说的', '懒得再绕', '话说到一半就笑了', '重新坐直'],
};

/** 查她在某个「已达最高关系阶段」的四招。查不到时返回空表与说明，由组件原样显示。 */
export function herSkillSet(stage: Stage): { skills: readonly string[]; note: string } {
  const set = HER_SKILL_SET[stage];
  return set ? { skills: set, note: '' } : { skills: [], note: `「${stage}」阶段招表待第二版产出（草案 §6.4）` };
}

/** 她名下的全部招（两套并集）。用于按招名反查归属，不必在正文里认人名。 */
const HER_SKILL_IDS = new Set(Object.values(HER_SKILL_SET).flatMap(set => [...(set ?? [])]));

/** 按招名反查归属。
 *
 * 用途是 `logic/battle-log.ts` 从本层正文摘「某某使出〈技能名〉」时判断这一招是谁出的：
 * 双方招表**互不相交**，按招名查表比在句子里认人名可靠得多（`<user>` 的名字面板并不知道）。
 * 表外的招返回 `未知`，由组件如实显示而不是随便归给一方。 */
export function skillOwner(id: string): '主角' | '朱小笋' | '未知' {
  if (HER_SKILL_IDS.has(id)) {
    return '朱小笋';
  }
  return Object.hasOwn(SKILLS, id) ? '主角' : '未知';
}

/** 查技能静态数值。MVU 的 `技能库`／`装备四槽` 允许出现本表没有的 id（如面板手输），
 * 那种情况返回 `null`，由组件显示「未登记」而不是崩掉或补默认值。 */
export function lookupSkill(id: string): SkillSpec | null {
  return Object.hasOwn(SKILLS, id) ? SKILLS[id] : null;
}
