import type { Schema } from '../../schema';
import { resetRounds, type StateName } from '../data/states';

/** 战斗侧的派生与两处状态机切换。组件只调这里，不各自拼 `决斗` 对象——
 * 开战要动十三个字段，散在组件里迟早漏掉一个。 */

/** 她在本场的生命上限 ＝ `朱小笋.$生命上限` × `决斗.$生命上限修正倍率`。
 *
 * 草案 §10.1 第五轮修订逐字：「修正只乘她的**生命上限**，不乘她的精力上限、不改她的四招威力」。
 *
 * **倍率在前端这一侧生效，不回写 `朱小笋.$生命上限`**，理由有二：
 *   一、§10.1 第六轮限定说「面板上『本场她的生命上限修正倍率』这个可编字段在质变决斗中
 *       没有作用对象」——反过来说在请愿决斗里它有作用对象，作用点就是这里；
 *   二、`$生命上限` 是 `关系.$已达最高关系阶段` 的派生（`logic/derive.ts`），战斗中若把倍率
 *       烧进去，玩家在常显头部改一下关系就会触发 `relationPatch` 把它按表改回原值，
 *       她的血上限会在对局中途悄悄腰斩。
 *
 * 已知代价（留给 B-G12 实测裁定，不在此处替它决定）：`世界书/阶段指导/决斗回合指导.txt:4`
 * 给模型的分母写的是未乘倍率的 `stat_data.朱小笋.$生命上限`，请愿决斗里会出现「生命 300 / 120」。
 *
 * **这条代价已经生效，不再是预留**：原注写的「第一版唯一的决斗是质变决斗、倍率恒 ×1.0，
 * 两种读法结果相同，故不动世界书」自 `openPetitionDuel()` 落地起不成立了——偏差 1–3 档的请愿决斗里
 * 模型看到的分母比面板小，她掉到 120 以下时模型会以为她已经见底。
 * **仍然不在这里顺手改世界书**：那是条目正文，而「分母该取哪一个」至今没有裁定，
 * `决斗回合指导` 与 `战斗叙事对照表` 两条都要跟着改口径。已记入留痕的未裁定项。 */
export function herHpCap(data: Schema): number {
  return Math.round(data.朱小笋.$生命上限 * data.决斗.$生命上限修正倍率);
}

/** 她的精力上限不受倍率影响（同上第五轮修订），直接取派生值。 */
export function herEpCap(data: Schema): number {
  return data.朱小笋.$精力上限;
}

/** 主角两项上限是持久可编字段，不派生、不受倍率影响。 */
export function youHpCap(data: Schema): number {
  return data.主角.生命上限;
}

export function youEpCap(data: Schema): number {
  return data.主角.精力上限;
}

/** 开战：`决斗` 组十三个字段一次置位。两条开战路（质变邀请、玩家请愿）共用。
 *
 * 双方生命精力开战置满、状态清空、两个「本场已用道具」标记复位（§8.1 整场只准用一次的计数口径）。
 * `$回合数` 置 0：第一次行动结算后才是第 1 回合，面板对它只读、不替脚本推进。
 *
 * **为什么两条路合成一个函数**：它们只差 `$本场为质变决斗` 与倍率两处，别的十一项一字不差。
 * 各写一份的代价不是重复本身，而是往后改开战口径时必漏一份——漏掉的若是
 * `$本场已用稀有道具` 这类复位，症状是「上一场用过的稀有道具这一场还是用不了」，几乎不会有人查到这里。
 *
 * 她的开战血量走 `herHpCap()`，喂一份换过倍率的数据视图进去，**不在这里重算「上限 × 倍率」**：
 * 「倍率只乘她的生命上限、不乘精力上限」这个非对称全卡只写在 `herHpCap()` 一处。 */
function openDuel(data: Schema, options: { qualitative: boolean; multiplier: number }): Pick<Schema, '决斗'> {
  const scaled = { ...data.决斗, $生命上限修正倍率: options.multiplier };
  return {
    决斗: {
      ...scaled,
      $是否在战斗中: true,
      $本场为质变决斗: options.qualitative,
      $回合数: 0,
      $朱小笋生命: herHpCap({ ...data, 决斗: scaled }),
      $朱小笋精力: herEpCap(data),
      $朱小笋状态: '无',
      $朱小笋状态剩余回合: 0,
      $主角生命: youHpCap(data),
      $主角精力: youEpCap(data),
      $主角状态: '无',
      $主角状态剩余回合: 0,
      $本场已用稀有道具: false,
      $本场朱小笋已用道具: false,
    },
  };
}

/** 接受质变邀请：开战。
 *
 * `决斗.$本场为质变决斗` 在 §5.8 字段落位表里属于「不提供控件的两项」之一，
 * 所以它不是一个能编的字段，而是**接受邀请这个动作的副产物**，在这里一次置位。
 *
 * 倍率恒 ×1.0：质变决斗不做偏差修正（§10.1 第六轮限定，准入已由好感度攒满承担）。 */
export function openQualitativeDuel(data: Schema): Pick<Schema, '决斗'> {
  return openDuel(data, { qualitative: true, multiplier: 1.0 });
}

/** 玩家在常态面板发起请愿决斗：开战，并吃下判档给出的偏差倍率。
 *
 * 与质变决斗的三处不同，别处一字不差：
 *   一、`$本场为质变决斗` 置假。§10.2 两条路的胜负后果完全不同：质变胜＝关系 +1 并清零好感度，
 *       请愿胜＝正文必须依请愿继续，而**请愿决斗的胜负本身不改好感度**（草案 §10.2 line 604/606）。
 *       那些结算跟 `closeDuel()` 一样不在本门实现位上，见该函数「有意不做的三件事」。
 *   二、倍率来自 `logic/duel-tier.ts` 的判档，不恒 ×1.0。
 *   三、§10.3 line 624：请愿决斗不设准入门槛、也没有冷却——所以本函数**不做任何前置判断**，
 *       没有「好感度够不够」「上一场打完没有」这类闸。空着是照裁定办，不是漏写。
 *
 * **倍率由调用方给，本函数不去调判档**：判档是一次会失败的网络调用，把它和十三个字段的同步置位
 * 缠在一起，「开战」就变成了一个可能失败的动作；而裁定 §10.1 line 595 要的正相反——
 * 「任何一层都不阻塞开战——挡住玩家发起决斗比判错档更糟」。判档失败时调用方照样拿 ×1.0 进来开战。 */
export function openPetitionDuel(data: Schema, multiplier: number): Pick<Schema, '决斗'> {
  return openDuel(data, { qualitative: false, multiplier });
}

/** 收场：把战斗态关掉，并清空全部战斗内临时态。
 *
 * **为什么收场这件事归前端**：`schema.ts:102` 给 `$是否在战斗中` 写的定义是
 * 「决斗回合指导 与 战斗叙事对照表 两条的显隐开关；**由前端组件调脚本写，不经模型**」。
 * 既然开战那两边（`openQualitativeDuel()`／`openPetitionDuel()`）都由前端写，关战这一边就不能指望模型——
 * 否则第一版会卡在战斗态里出不来，而 `$是否在战斗中` 并不在 §5.8 可编字段表内，
 * 玩家连手动兜底的入口都没有。
 *
 * 清空的依据是 `世界书/阶段指导/决斗回合指导.txt:44`：「生命、精力、状态都不带进后面的场景」。
 * `$生命上限修正倍率` 一并回到 ×1.0，免得下一场请愿决斗继承上一场的档位。
 *
 * **有意不做的三件事**（§10.2 的胜负后果，本函数一个都不碰）：
 * 关系 +1、好感度清零、好感度 −5。理由是它们属于结算，而「脚本写 MVU 的确切 API 与该挂哪个
 * 事件」至今是 B-G7 的未结项（design-spec §9 第 28 项第三条欠账），本门不替它发明实现位置。
 * 第一版里这三项要么由模型那一拍的 `<UpdateVariable>` 写，要么玩家用常态面板的关系／好感度
 * 编辑手动兜底——这是如实记下的缺口，不是顺手补掉的细节。 */
export function closeDuel(data: Schema): Pick<Schema, '决斗'> {
  return {
    决斗: {
      ...data.决斗,
      $是否在战斗中: false,
      $本场为质变决斗: false,
      $生命上限修正倍率: 1.0,
      $回合数: 0,
      $朱小笋生命: 0,
      $朱小笋精力: 0,
      $朱小笋状态: '无',
      $朱小笋状态剩余回合: 0,
      $主角生命: 0,
      $主角精力: 0,
      $主角状态: '无',
      $主角状态剩余回合: 0,
      $本场已用稀有道具: false,
      $本场朱小笋已用道具: false,
    },
  };
}

/** 点「暂缓」：记下**当前所处的关系段名**（草案 §1.4）。
 *
 * 存段名而不是存布尔，于是「推进到下一段又满 100 则再弹一次」自动成立（design-spec §5.7.3）——
 * 这也是 StatusBar 判邀请态时比的是 `$邀请暂缓于 !== _当前关系` 而不是一个 flag 的原因。
 * 好感度不动：暂缓不是失败，§10.2 的 −5 只在质变决斗打输时结算。 */
export function deferInvite(data: Schema): Pick<Schema, '关系'> {
  return { 关系: { ...data.关系, $邀请暂缓于: data.关系._当前关系 } };
}

/** 战斗内编辑提交时的一侧补丁：状态与**剩余回合**必须一起写。
 *
 * §5.8 九项⑦：剩余回合不单独编辑，随所选状态自动重置到草案 §7.2 的固定回合数；
 * 「被拿住」「乱了阵脚」没有固定回合数，归 0 由面板显示「—」。 */
export function sideStatePatch(name: StateName): { 状态: StateName; 剩余回合: number } {
  return { 状态: name, 剩余回合: resetRounds(name) };
}
