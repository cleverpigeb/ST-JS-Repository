// 《闷骚女友朱小笋》MVU 变量结构（B-G7）
// 权威来源：创作规划.yaml 的 mvu 段（37 条 variables，一条不多一条不少）与 亲密决斗-规则草案.md
//
// 前缀是变量名的一部分，key 必须原样带前缀：
//   无前缀 ＝ AI 可见 + AI 可更新    _ ＝ AI 可见、AI 不可更新（脚本可写）
//   $      ＝ AI 不可见、AI 不可更新（脚本可写）
//
// 集合形态：定长集合一律固定键 z.record(z.enum([...]))，不定长集合用 z.record(z.string())；
//   全卡不用数组——模型可以发 `remove /path/0`，数组按索引删会让其后各项整体错位且无法自愈。
//
// 三类跨字段约束由脚本负责，本文件只在对应字段上注明、不实现：
//   只增不减（关系.$已达最高关系阶段）、派生（朱小笋.$生命上限／$精力上限）、
//   搬移（事件.进行中 → 事件.$历史区）。

export const Schema = z.object({
  场景: z.object({
    // 格式 YYYY/MM/DD-HH:MM。不用 z.templateLiteral 硬校验：模型写成别的格式时
    // 整份变量更新会被丢弃，代价大于收益，格式要求写在 变量更新规则 里。
    时间: z.string().prefault('待初始化'),
    // 常见取 world.regions[0].scenes 之一，也可以是校外地点，不受该表封闭
    地点: z.string().prefault('待初始化'),
  }).prefault({}),

  关系: z.object({
    // 草案 §1 七段，逐级 ±1 不跳段。脚本独写：决斗结算／好感度结算触发回退／
    // 面板提交／开局初始化四条路径。
    _当前关系: z.enum(['同学', '朋友', '暧昧', '恋人', '亲密恋人', '订婚', '结婚']).prefault('恋人'),
    // 好感度满 100 时由脚本置真；面板只读
    _质变决斗已解锁: z.boolean().prefault(false),
    // 一次性叙事信号：脚本在回退发生的那一拍置真，下一拍复位为假（草案 §1.3 第三条）
    _关系刚刚回退: z.boolean().prefault(false),
    // 模型侧唯一入口：每拍只报 −5…5 的**整数**增量（草案 §1.1），脚本累加进 $好感度 后复位为 0。
    // 夹取与取整都是草案明确写下的限制，故用 transform 而非 min/max/int，避免超界时整条更新被丢弃。
    好感度本轮增量: z.coerce.number().transform(value => _.clamp(Math.round(value), -5, 5)).prefault(0),
    // 0–100 的**整数**总值，模型读不到（草案 §1.1）。prefault 取恋人开局的 80，真实初值以 initvar 为准；
    // 不取 0 是因为 0 是 §1.3 回退的触发区，自愈到 0 配上 $回退预备 为真会误触发掉级。
    $好感度: z.coerce.number().transform(value => _.clamp(Math.round(value), 0, 100)).prefault(80),
    // 回退的前置闸：减值把总值夹到 0 时置真，清零或任何正增量时置假（草案 §1.3 第四条）
    $回退预备: z.boolean().prefault(false),
    // 存「点暂缓时所处的关系段名」，空串＝没暂缓过（草案 §1.4）
    $邀请暂缓于: z.enum(['', '同学', '朋友', '暧昧', '恋人', '亲密恋人', '订婚', '结婚']).prefault(''),
    // 只增不减，由脚本维护（草案 §1.3 第二条）；本 schema 不实现该约束。
    // 战斗侧派生（她的两项上限、招表、清醒度 k、她的背包件数）与解锁派发一律查它，
    // 正文侧（行为上界、偏差判档锚点）查 _当前关系，两条锚不可互换。
    $已达最高关系阶段: z.enum(['同学', '朋友', '暧昧', '恋人', '亲密恋人', '订婚', '结婚']).prefault('恋人'),
  }).prefault({}),

  朱小笋: z.object({
    心情: z.string().prefault('待初始化'),
    心里话: z.string().prefault('待初始化'),
    // 固定 3 格，空格写成名称空串、数量 0。初始件数按 关系.$已达最高关系阶段 查草案 §12.3
    // （恋人 1 件、亲密恋人 2 件）；每格数量上限取该道具档位的堆叠上限；她不获得稀有道具。
    背包: z.record(z.enum(['格1', '格2', '格3']), z.object({
      名称: z.string().prefault(''),
      数量: z.coerce.number().prefault(0),
    }).prefault({})).prefault({ 格1: {}, 格2: {}, 格3: {} }),
    // 派生只读，不是独立持久字段：按 关系.$已达最高关系阶段 查草案 §5 表，由脚本写入。
    // 本 schema 不实现派生；prefault 取恋人档的 120，与 $已达最高关系阶段 的 prefault 对齐。
    $生命上限: z.coerce.number().prefault(120),
    // 派生只读：＝ $生命上限 ÷ 2 向下取整到 5 的倍数，由脚本写入（恋人档 60）
    $精力上限: z.coerce.number().prefault(60),
  }).prefault({}),

  主角: z.object({
    // 面板可编，下限＝该开局的初始值（恋人开局 100，草案 §12.4）；
    // 剧情层唯一的抬升渠道是专属任务（第一版 +35）。下限由前端把关，schema 不夹。
    生命上限: z.coerce.number().prefault(100),
    // 面板可编，下限 50；剧情层唯一抬升渠道同上（第一版 +15）
    精力上限: z.coerce.number().prefault(50),
    // 不定长：键＝技能 id，值＝是否已获得，无上限。技能表本体在根级 $技能表
    // （B-G10 实测后改判：原方案把表体劈成前端静态表与条目正文两半，编辑态改不到，且
    //  决斗回合指导 承诺的「威力／命中／精力由脚本给出」无来源。详见 创作规划.yaml mvu 段）。
    技能库: z.record(z.string().describe('技能 id'), z.boolean().prefault(true)).prefault({}),
    // 恒 4 槽，值＝技能 id，只替换不增减，只能在战斗外更换。空串仅作结构自愈占位，
    // 恋人开局四槽由 initvar 填满。
    装备四槽: z.record(z.enum(['槽1', '槽2', '槽3', '槽4']), z.string().prefault(''))
      .prefault({ 槽1: '', 槽2: '', 槽3: '', 槽4: '' }),
    // 固定 3 格，空格写成名称空串、数量 0。初始 2 件（草案 §8.2 薄荷糖、纸巾，第 3 格空）；
    // 每格数量上限取该道具档位的堆叠上限（§8.1 常见 3／精良 2／稀有 1）。
    背包: z.record(z.enum(['格1', '格2', '格3']), z.object({
      名称: z.string().prefault(''),
      数量: z.coerce.number().prefault(0),
    }).prefault({})).prefault({ 格1: {}, 格2: {}, 格3: {} }),
  }).prefault({}),

  // 技能表本体（草案 §6.1 字段表），键＝技能 id，不定长。放在根级而非 主角 下：
  // 表里同时装两方的招（阵营 字段区分），主角侧 4 招＋她当前段 4 招由 战斗叙事对照表 渲染。
  // 全部 $：面板全字段可编，模型既看不见也写不了；维度约束（威力／命中／精力 的档位）
  // 由前端提交时把关，与 §11.4「夹取是前端提交时的职责」同口径，本处只保形状不夹范围。
  // 「来源（初始／剧情解锁）」不入本表，那件事由 主角.技能库 的布尔值承担，避免同一事实存两处。
  $技能表: z.record(
    z.string().describe('技能 id'),
    z.object({
      阵营: z.enum(['主角', '朱小笋']).prefault('主角'),
      // 她按段换招，主角的招不分段写「通用」；渲染时按此字段筛选
      适用段: z.enum(['通用', '同学', '朋友', '暧昧', '恋人', '亲密恋人', '订婚', '结婚']).prefault('通用'),
      类别: z.enum(['攻击', '变化']).prefault('攻击'),
      威力: z.coerce.number().prefault(0),
      命中: z.coerce.number().prefault(0),
      // 变化类无暴击，写 0 表示没有这一项
      暴击: z.coerce.number().prefault(0),
      精力: z.coerce.number().prefault(0),
      附加效果: z.string().prefault(''),
      叙事指导: z.string().prefault(''),
    }).prefault({}),
  ).prefault({}),

  事件: z.object({
    // 不定长：键＝事件名，无上限；面板支持增删改、标记完成、从历史区取回
    进行中: z.record(z.string().describe('事件名'), z.object({
      进度: z.string().prefault('待初始化'),
    }).prefault({})).prefault({}),
    // 已完成事件，不注入提示词。搬移（进行中 → 历史区）由脚本执行，模型不参与，
    // 本 schema 不做搬移 transform。
    $历史区: z.record(z.string().describe('事件名'), z.object({
      进度: z.string().prefault('待初始化'),
    }).prefault({})).prefault({}),
  }).prefault({}),

  // 决斗组全部 $：战斗内临时态，战斗结束由脚本重置；仅经 决斗回合指导 用 EJS 渲染给模型。
  // 生命与精力一律不加 min/max/clamp——草案 §11.4 明文「生命与精力的输入在提交时自动夹在
  // 0 至该方当前上限之间，不做提交后校验」：夹取是前端提交时的职责，schema 侧再校验会把
  // 玩家的手动兜底改坏。战斗外这些值无意义，prefault 一律 0，开战时由脚本置满。
  决斗: z.object({
    // 决斗回合指导 与 战斗叙事对照表 两条的显隐开关；由前端组件调脚本写，不经模型
    $是否在战斗中: z.boolean().prefault(false),
    // 区分质变决斗与普通请愿决斗：偏差倍率（草案 §10.1）与胜负后果（§10.2）都要靠它。
    // true 时偏差修正恒 ×1.0、胜利后关系 +1 并清零好感度。由脚本在开战时置位、战后重置。
    $本场为质变决斗: z.boolean().prefault(false),
    // 面板唯一不可编的显示变量；自由文本不推进回合
    $回合数: z.coerce.number().prefault(0),
    $朱小笋生命: z.coerce.number().prefault(0),
    $朱小笋精力: z.coerce.number().prefault(0),
    // 草案 §7.2 十种 +「无」单选：轻三种／中五种／重两种。效果与消退回合数是脚本侧静态表，
    // 不进变量；正文不得点名状态，状态在剧情里没有名字，也不被角色感知。
    $朱小笋状态: z.enum(['无', '越想越羞', '心跳失速', '面不改色', '脸在烧', '被拿住', '讲不出话', '沉不住气', '乱了阵脚', '腿软', '僵住']).prefault('无'),
    // 不单独编辑，随所选状态按草案 §7.2 自动重置
    $朱小笋状态剩余回合: z.coerce.number().prefault(0),
    $主角生命: z.coerce.number().prefault(0),
    $主角精力: z.coerce.number().prefault(0),
    $主角状态: z.enum(['无', '越想越羞', '心跳失速', '面不改色', '脸在烧', '被拿住', '讲不出话', '沉不住气', '乱了阵脚', '腿软', '僵住']).prefault('无'),
    $主角状态剩余回合: z.coerce.number().prefault(0),
    // 草案 §10.1 四档：偏差 0 档 ×1.0、1 档 ×1.5、2 档 ×2.5、3 档 ×4.0
    // （恋人开局对应 120／180／300／480 生命）。z.enum 只收字符串，数值四档改用
    // 「就近吸附到四档」的 transform：面板 select 传回的字符串 "1.5" 也能收下，
    // 落到档外的值吸附到最近一档而不是让整份更新失败。质变决斗恒 ×1.0 由脚本保证，
    // 本字段看不到 $本场为质变决斗，也不该在此跨字段联动（面板兜底优先，§11.4）。
    $生命上限修正倍率: z.coerce.number()
      .transform(value => _.minBy([1.0, 1.5, 2.5, 4.0], tier => Math.abs(tier - value)) ?? 1.0)
      .prefault(1.0),
    // 整场稀有道具只准用一次（草案 §8.1），主角侧
    $本场已用稀有道具: z.boolean().prefault(false),
    $本场朱小笋已用道具: z.boolean().prefault(false),
  }).prefault({}),
});

export type Schema = z.output<typeof Schema>;
